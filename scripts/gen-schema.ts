// Regenerates server/schema.sql from src/data/nigeriaStates.ts. Run: npx tsx scripts/gen-schema.ts
import { writeFileSync } from 'node:fs';
import { NIGERIAN_STATES } from '../src/data/nigeriaStates';

const q = (v: string | null) => (v === null ? 'NULL' : `'${v.replace(/'/g, "''")}'`);
const codes = NIGERIAN_STATES.map((s) => q(s.code)).join(', ');

const stateRows = NIGERIAN_STATES.map(
  (s) => `    (${q(s.code)}, ${q(s.name)}, ${q(s.capital)}, ${q(s.zone)}, ${q(s.disco)})`
).join(',\n');

// Sample feeders for FCT and Lagos, plus a city-wide capital area for every other state
const samples: Array<[string, string, string, string, string | null, number | null]> = [
  ['fc-gwarinpa-01', 'FC', 'Gwarinpa (3rd Ave / 6th Ave Feeder)', 'AEDC', 'Band A', 209.5],
  ['fc-wuse2-01', 'FC', 'Wuse II / Aminu Kano Crescent', 'AEDC', 'Band A', 209.5],
  ['fc-lugbe-01', 'FC', 'Lugbe FHA / Airport Road Feeder', 'AEDC', 'Band B', 68.2],
  ['fc-kubwa-01', 'FC', 'Kubwa Phase 4 / Arab Road', 'AEDC', 'Band B', 68.2],
  ['la-ikeja-01', 'LA', 'Ikeja Allen / Opebi Feeder', 'IKEDC', 'Band A', 209.5],
  ['la-surulere-01', 'LA', 'Surulere Bode Thomas / Adeniran Ogunsanya', 'EKEDC', 'Band A', 209.5],
  ['la-lekki1-01', 'LA', 'Lekki Phase 1 / Admiralty Way', 'EKEDC', 'Band A', 209.5],
  ['la-yaba-01', 'LA', 'Yaba Akoka / Herbert Macaulay', 'EKEDC', 'Band B', 68.2]
];
const capitals = NIGERIAN_STATES.filter((s) => s.code !== 'FC' && s.code !== 'LA').map(
  (s) => [`${s.code.toLowerCase()}-capital`, s.code, `${s.capital} (city-wide)`, s.disco, null, null] as const
);
const zoneRows = [...samples, ...capitals]
  .map(([id, code, hood, disco, band, rate]) =>
    `    (${q(id)}, ${q(code)}, ${q(hood)}, ${q(disco)}, ${q(band)}, ${rate === null ? 'NULL' : rate.toFixed(2)})`
  )
  .join(',\n');

const sql = `-- ============================================================================
-- LIGHTLINE ("WETIN DEY?") - POSTGRESQL SCHEMA (Neon or any Postgres 13+)
-- Covers all 36 states + FCT. Generated by scripts/gen-schema.ts; safe to re-run.
-- The server runs this automatically on start, so a new Neon database needs no manual step.
-- ============================================================================


-- 0. STATES (ISO 3166-2:NG codes without the "NG-" prefix)
CREATE TABLE IF NOT EXISTS public.ng_states (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    capital TEXT NOT NULL,
    geo_zone TEXT NOT NULL,
    primary_disco TEXT NOT NULL
);

INSERT INTO public.ng_states (code, name, capital, geo_zone, primary_disco)
VALUES
${stateRows}
ON CONFLICT (code) DO UPDATE SET
    name = EXCLUDED.name,
    capital = EXCLUDED.capital,
    geo_zone = EXCLUDED.geo_zone,
    primary_disco = EXCLUDED.primary_disco;

-- 1. AREAS / FEEDER ZONES (seeded per state; users add their own street, estate or feeder)
CREATE TABLE IF NOT EXISTS public.feeder_zones (
    id TEXT PRIMARY KEY,
    state_code TEXT NOT NULL REFERENCES public.ng_states(code),
    neighborhood TEXT NOT NULL,
    disco_name TEXT NOT NULL,
    tariff_band TEXT CHECK (tariff_band IN ('Band A', 'Band B', 'Band C', 'Band D', 'Band E')),
    tariff_rate_ngn_kwh NUMERIC(8,2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_feeder_zones_state ON public.feeder_zones (state_code);

-- 2. CROWDSOURCED POWER PINGS (Up NEPA / They Have Taken Light)
CREATE TABLE IF NOT EXISTS public.power_pings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    client_mutation_id TEXT UNIQUE NOT NULL,
    zone_id TEXT NOT NULL REFERENCES public.feeder_zones(id) ON DELETE CASCADE,
    grid_state TEXT NOT NULL CHECK (grid_state IN ('ON_GRID', 'OFF_GRID', 'LOW_VOLTAGE')),
    voltage_estimate INTEGER DEFAULT 220,
    detected_via TEXT NOT NULL DEFAULT 'MANUAL' CHECK (detected_via IN ('MANUAL', 'CHARGER_HOOK')),
    reporter_alias TEXT DEFAULT 'Neighbor',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_power_pings_zone_time ON public.power_pings (zone_id, created_at DESC);

-- 3. BANK & POS NETWORK TELEMETRY LOGS (bank outages are national; state kept for later slicing)
CREATE TABLE IF NOT EXISTS public.bank_telemetry_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    client_mutation_id TEXT UNIQUE NOT NULL,
    institution_id TEXT NOT NULL,
    institution_name TEXT NOT NULL,
    institution_type TEXT NOT NULL CHECK (institution_type IN ('FINTECH', 'COMMERCIAL_BANK')),
    channel TEXT NOT NULL CHECK (channel IN ('APP_TRANSFER', 'POS_CARD', 'USSD')),
    outcome TEXT NOT NULL CHECK (outcome IN ('INSTANT', 'DELAYED', 'FAILED_REVERSED', 'HANGING')),
    latency_seconds INTEGER NOT NULL DEFAULT 15,
    state_code TEXT REFERENCES public.ng_states(code),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bank_telemetry_inst_time ON public.bank_telemetry_logs (institution_id, created_at DESC);

-- 4. FUEL PUMP, GAS & COMMUTE FARE REPORTS
CREATE TABLE IF NOT EXISTS public.market_radar_reports (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    client_mutation_id TEXT UNIQUE NOT NULL,
    state_code TEXT NOT NULL REFERENCES public.ng_states(code),
    category TEXT NOT NULL CHECK (category IN ('PMS_FUEL', 'DIESEL', 'COOKING_GAS', 'ROUTE_FARE')),
    location_title TEXT NOT NULL,
    price_ngn NUMERIC(10,2) NOT NULL CHECK (price_ngn > 0 AND price_ngn < 1000000),
    unit_label TEXT NOT NULL,
    queue_severity TEXT NOT NULL CHECK (queue_severity IN ('NO_QUEUE', 'MOVING_FAST', 'LONG_HOLDUP', 'LOCKED_UP')),
    pos_accepted BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_market_radar_state_time ON public.market_radar_reports (state_code, created_at DESC);

-- 5. LIVE VIEW: AREA POWER STATUS. Areas nobody has reported show UNKNOWN, never a guess.
CREATE OR REPLACE VIEW public.v_live_neighborhood_power AS
SELECT
    fz.id AS zone_id,
    fz.state_code,
    fz.neighborhood,
    fz.disco_name,
    fz.tariff_band,
    fz.tariff_rate_ngn_kwh,
    COALESCE(latest.grid_state, 'UNKNOWN') AS current_state,
    COALESCE(latest.created_at, 'epoch'::timestamptz) AS last_updated_at,
    COALESCE(stats.confirmations_last_90m, 0) AS recent_confirmations,
    COALESCE(stats.avg_voltage, 0) AS estimated_voltage
FROM public.feeder_zones fz
LEFT JOIN LATERAL (
    SELECT grid_state, created_at
    FROM public.power_pings pp
    WHERE pp.zone_id = fz.id
    ORDER BY pp.created_at DESC
    LIMIT 1
) latest ON TRUE
LEFT JOIN LATERAL (
    SELECT
        COUNT(*) AS confirmations_last_90m,
        ROUND(AVG(voltage_estimate))::INT AS avg_voltage
    FROM public.power_pings pp2
    WHERE pp2.zone_id = fz.id
      AND pp2.created_at >= NOW() - INTERVAL '90 minutes'
) stats ON TRUE;

-- 6. LIVE VIEW: BANK & POS NETWORK WEATHER (last 60 minutes, national)
CREATE OR REPLACE VIEW public.v_live_bank_weather AS
SELECT
    institution_id,
    MAX(institution_name) AS institution_name,
    MAX(institution_type) AS institution_type,
    channel,
    COUNT(*) AS total_reports_60m,
    ROUND(
        (SUM(CASE
            WHEN outcome = 'INSTANT' THEN 1.0
            WHEN outcome = 'DELAYED' THEN 0.5
            ELSE 0.0
        END) / GREATEST(COUNT(*), 1)) * 100
    )::INT AS success_rate_pct,
    ROUND(AVG(latency_seconds))::INT AS avg_latency_sec,
    MAX(created_at) AS last_reported_at
FROM public.bank_telemetry_logs
WHERE created_at >= NOW() - INTERVAL '60 minutes'
GROUP BY institution_id, channel;

-- 7. SEED AREAS: sample feeders for FCT and Lagos, a city-wide capital area for every other state
INSERT INTO public.feeder_zones (id, state_code, neighborhood, disco_name, tariff_band, tariff_rate_ngn_kwh)
VALUES
${zoneRows}
ON CONFLICT (id) DO NOTHING;

-- Only the Lightline server connects to this database. Phones never write to it directly.
`;

writeFileSync(new URL('../server/schema.sql', import.meta.url), sql);
console.log(`schema.sql written: ${NIGERIAN_STATES.length} states, ${samples.length + capitals.length} seed areas`);
